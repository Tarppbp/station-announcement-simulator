S2J = {_PAIRS[i]: _PAIRS[i+1] for i in range(0, len(_PAIRS) - 1, 2)}


def to_japanese(name):
    """(Japanese written form, English or None, fixed reading or None) for a station name typed in Chinese."""
    name = str(name).strip()
    if name in FOREIGN:
        jp, en = FOREIGN[name]
        return jp, en, CITY_READING.get(jp)
    out = name
    for zh in sorted(WORDS, key=len, reverse=True):
        out = out.replace(zh, WORDS[zh])
    out = ''.join(S2J.get(c, c) for c in out)
    if out.endswith('站') and len(out) > 1: out = out[:-1] + '駅'   # 东京站 -> 東京駅
    return out, None, CITY_READING.get(out)
